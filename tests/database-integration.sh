#!/usr/bin/env bash
# Explicit opt-in Docker test. Uses only uniquely named temporary resources.
set -euo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
tmp="$(mktemp -d)"
project="local-db-test-$(date +%s)-$$"
volume="$project-data"
compose=(docker compose --env-file "$root/database/.env.example" -f "$root/database/compose.yaml" -f "$tmp/override.yaml" -p "$project")
cleanup() {
  "${compose[@]}" down --volumes >/dev/null
  docker volume rm "$volume" >/dev/null
  rm -rf -- "$tmp"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
umask 077
# Includes quotes/backslashes to exercise SQL literal handling in init-app.sh.
printf '%s' 'integration-admin-only' > "$tmp/admin-password"
printf '%s' "integration-app-quote'and\\slash" > "$tmp/app-password"
export LOCAL_DB_SECRETS_DIR="$tmp"
cat > "$tmp/override.yaml" <<EOF
services:
  postgres:
    ports: !override
      - target: 5432
        published: "0"
        host_ip: 127.0.0.1
volumes:
  postgres-data:
    name: $volume
EOF
docker volume create "$volume" >/dev/null
"${compose[@]}" up -d --wait --wait-timeout 120 postgres
client=("${compose[@]}" exec -T postgres sh -c 'export PGPASSWORD="$(cat /run/secrets/app_password)"; exec "$@"' sh)
published="$("${compose[@]}" port postgres 5432)"
host_port="${published##*:}"
# Exercise the same Docker Desktop host route used by kind nodes, on a random
# loopback-only test port. Actual Pod connectivity remains a deployment preflight.
"${client[@]}" env PGCONNECT_TIMEOUT=5 psql -h host.docker.internal -p "$host_port" -U myfastapiapp -d myfastapiapp -X -Atqc 'SELECT 1'
# The restore helper must accept a fresh schema and reject function-only data too.
schema_objects="SELECT count(*) FROM pg_depend WHERE refclassid = 'pg_namespace'::regclass AND refobjid = 'public'::regnamespace"
[[ "$("${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d myfastapiapp -X -Atqc "$schema_objects")" == 0 ]]
"${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d myfastapiapp -X -v ON_ERROR_STOP=1 -c 'CREATE FUNCTION public.restore_guard_test() RETURNS integer LANGUAGE sql AS $$ SELECT 1 $$;' >/dev/null
[[ "$("${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d myfastapiapp -X -Atqc "$schema_objects")" != 0 ]]
"${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d myfastapiapp -X -v ON_ERROR_STOP=1 -c 'DROP FUNCTION public.restore_guard_test();' >/dev/null
"${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d myfastapiapp -X -v ON_ERROR_STOP=1 <<'SQL'
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = current_user AND
    (rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication OR rolbypassrls)) THEN
    RAISE EXCEPTION 'app has elevated privileges';
  END IF;
END $$;
CREATE TABLE public.retained_data (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text);
INSERT INTO public.retained_data (value) VALUES ('survives restore');
SQL
"${client[@]}" pg_dump -h 127.0.0.1 -U myfastapiapp -d myfastapiapp -Fc --no-owner --no-acl > "$tmp/backup.dump"
"${compose[@]}" exec -T postgres createdb -U postgres --owner=myfastapiapp restore_check
"${client[@]}" pg_restore -h 127.0.0.1 -U myfastapiapp -d restore_check --no-owner --no-acl --single-transaction --exit-on-error < "$tmp/backup.dump"
restored="$("${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d restore_check -X -Atqc 'SELECT value FROM public.retained_data')"
[[ "$restored" == 'survives restore' ]]
# Also restore a legacy superuser-owned archive using the restricted login.
"${compose[@]}" exec -T postgres psql -X -U postgres -d myfastapiapp -v ON_ERROR_STOP=1 -c "CREATE TABLE legacy_owned (value text); INSERT INTO legacy_owned VALUES ('legacy');" >/dev/null
"${compose[@]}" exec -T postgres pg_dump -U postgres -d myfastapiapp -Fc > "$tmp/legacy.dump"
"${compose[@]}" exec -T postgres createdb -U postgres --owner=myfastapiapp legacy_check
"${client[@]}" pg_restore -h 127.0.0.1 -U myfastapiapp -d legacy_check --no-owner --no-acl --single-transaction --exit-on-error < "$tmp/legacy.dump"
owner="$("${client[@]}" psql -h 127.0.0.1 -U myfastapiapp -d legacy_check -X -Atqc "SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid = 'legacy_owned'::regclass")"
[[ "$owner" == myfastapiapp ]]
"${compose[@]}" down --volumes
# The external volume survives even down --volumes.
docker volume inspect "$volume" >/dev/null
printf 'PostgreSQL host routing, app grants, restore guard, backup/restore, legacy ownership and external volume retention passed.\n'
